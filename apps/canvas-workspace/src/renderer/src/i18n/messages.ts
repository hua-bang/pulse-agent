export type I18nKey = keyof typeof enMessages;
export type MessageCatalog = Record<I18nKey, string>;

// English ships in the entry chunk as the fallback catalog. Other languages
// load on demand, so the entry does not carry every translation.
const catalogLoaders: Partial<Record<LanguageCode, () => Promise<MessageCatalog>>> = {
  zh: () => import('./messages-zh').then(module => module.zhMessages),
};
const catalogs: Partial<Record<LanguageCode, MessageCatalog>> = { en: enMessages };

/** The loaded catalog for a language, or English until it has loaded. */
export function getMessages(language: LanguageCode): MessageCatalog {
  return catalogs[language] ?? enMessages;
}

/** Loads a language's catalog. Resolves at once when it is loaded already. */
export async function loadMessages(language: LanguageCode): Promise<void> {
  if (catalogs[language]) return;
  const load = catalogLoaders[language];
  if (load) catalogs[language] = await load();
}
